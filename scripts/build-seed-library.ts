// Builds supabase/seed_library.sql from supabase/seed/recipes.json.
// Every ingredient line goes through the same parser and catalogue match as
// the import-recipe function, and macros are estimated the same way, so seed
// recipes behave exactly like imported ones.
//
// The catalogue is read from a database that has the migrations and seed.sql
// applied (npm run test:sql leaves one behind as dineamite_test):
//   node scripts/build-seed-library.ts          # check, report, write the SQL
//   node scripts/build-seed-library.ts --check  # check and report only
// Exits 1 when a line doesn't match the catalogue or a recipe is malformed.

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import {
  Catalog, estimateMacros, gramsOf, parseIngredientLine, type CatalogEntry,
} from '../supabase/functions/_shared/logic/ingredients.ts';
import { DIFFICULTIES, SPECIAL_EQUIPMENT, normaliseEquipment, type Difficulty, type Equipment } from '../supabase/functions/_shared/logic/facets.ts';

interface SeedIngredient { id: string; text: string; original_text?: string; guessed?: boolean; optional?: boolean }
interface SeedRecipe {
  /** Fixed uuid: the recipe has this id in every database. */
  id: string;
  title: string;
  language: 'en' | 'fr' | 'it';
  servings: number;
  original_servings?: number;
  /** Start to plate. Only when there's waiting time too (marinating, rising, resting); otherwise prep + cook. */
  total_min?: number;
  prep_min: number;
  cook_min: number;
  source_type?: string;
  source_name?: string;
  /** Required, except for AI-generated recipes, which have no source. */
  source_url?: string | null;
  ai_generated_recipe?: boolean;
  image_url?: string | null;
  image_source_url?: string | null;
  cuisine?: string;
  tags: string[];
  difficulty: Difficulty;
  equipment: Equipment;
  ingredients: SeedIngredient[];
  steps: string[];
}

const root = new URL('..', import.meta.url).pathname;
const checkOnly = process.argv.includes('--check');
const db = process.env.PGDATABASE ?? 'dineamite_test';

const entries = JSON.parse(execFileSync('psql', ['-At', '-d', db, '-c',
  'select coalesce(json_agg(c), \'[]\') from public.ingredient_catalog c'], { encoding: 'utf8' })) as CatalogEntry[];
if (entries.length === 0) throw new Error(`no catalogue in database ${db}: run npm run test:sql first`);
const catalog = new Catalog(entries);
const recipes = JSON.parse(readFileSync(`${root}supabase/seed/recipes.json`, 'utf8')) as SeedRecipe[];

const errors: string[] = [];
const warnings: string[] = [];
const seenKeys = new Set<string>();
const seenIds = new Set<string>();
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
function checkId(id: string, what: string) {
  if (!UUID.test(id ?? '')) errors.push(`${what} needs an id (a lowercase uuid)`);
  else if (seenIds.has(id)) errors.push(`${what} has the duplicate id ${id}`);
  else seenIds.add(id);
}

// How seed recipes loaded before they had fixed ids are recognised: their
// source_url, or language and title for AI-generated recipes without one.
const keyOf = (r: SeedRecipe) => r.source_url ?? `${r.language}:${r.title.trim().slice(0, 200)}`;
const keySql = (alias: string) => `coalesce(${alias}.source_url, ${alias}.language || ':' || ${alias}.title)`;

function lit(v: unknown): string {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${String(v).replace(/'/g, "''")}'`;
}

const out: string[] = [
  '-- Generated by scripts/build-seed-library.ts from supabase/seed/recipes.json. Do not edit.',
  '-- Seed recipes (household_id null), with the fixed ids from recipes.json. Re-running skips',
  '-- recipes already loaded and brings the ones loaded earlier up to date.',
  'begin;',
];
const inserts: string[] = [];
const adoptRecipes: string[] = [];
const adoptLines: string[] = [];
const summary: string[] = [];
const facets: string[] = [];
const times: string[] = [];
const names: string[] = [];
const macroRows: string[] = [];

for (const r of recipes) {
  const where = `${r.title}:`;
  checkId(r.id, where);
  r.ingredients.forEach((i, n) => checkId(i.id, `${where} line ${n + 1}`));
  if (!['en', 'fr', 'it'].includes(r.language)) errors.push(`${where} language ${r.language}`);
  if (!(r.servings > 0)) errors.push(`${where} servings ${r.servings}`);
  if (!r.source_url && !r.ai_generated_recipe) errors.push(`${where} no source_url`);
  if (r.source_url && !/^https?:\/\//.test(r.source_url)) errors.push(`${where} source_url must be a link`);
  const key = keyOf(r);
  if (seenKeys.has(key)) errors.push(`${where} duplicate ${r.source_url ? 'source_url' : 'language and title'}`);
  seenKeys.add(key);
  if (r.tags.length > 12) errors.push(`${where} ${r.tags.length} tags (max 12)`);
  if (r.tags.some((t) => t !== t.toLowerCase().trim())) errors.push(`${where} tags must be lowercase`);
  if (r.cuisine && !r.tags.includes(r.cuisine)) warnings.push(`${where} cuisine "${r.cuisine}" missing from tags`);
  if (!r.steps.length) errors.push(`${where} no steps`);
  if (!DIFFICULTIES.includes(r.difficulty)) errors.push(`${where} difficulty ${r.difficulty}`);
  const equipment = normaliseEquipment(r.equipment);
  if (JSON.stringify(equipment) !== JSON.stringify(r.equipment)) {
    errors.push(`${where} equipment must be { pots: whole number, oven: true/false, special: [...] } in display order`);
  }
  if (!equipment.pots && !equipment.special.includes('barbecue')) errors.push(`${where} no pots, pans or barbecue`);
  for (const k of equipment.special) {
    if (!(SPECIAL_EQUIPMENT as readonly string[]).includes(k)) errors.push(`${where} unknown special equipment "${k}"`);
  }
  if (r.image_url?.startsWith('/')) {
    // Photos the app serves itself live in web/public.
    if (!existsSync(`${root}web/public${r.image_url}`)) errors.push(`${where} photo ${r.image_url} not found in web/public`);
  } else if (r.image_url && !r.image_url.startsWith('https://')) errors.push(`${where} image_url must be https:// or /recipe-photos/…`);
  for (const k of ['prep_min', 'cook_min'] as const) {
    if (!Number.isInteger(r[k]) || r[k] < 0) errors.push(`${where} ${k} must be a whole number of minutes`);
  }
  const totalMin = r.total_min ?? r.prep_min + r.cook_min;
  if (r.total_min !== undefined && r.total_min <= r.prep_min + r.cook_min) {
    errors.push(`${where} total_min ${r.total_min} isn't more than prep + cook: leave it out`);
  }
  if (!(totalMin > 0)) errors.push(`${where} no time`);
  const ratio = r.original_servings ? r.servings / r.original_servings : 1;

  const ingredients = r.ingredients.map((i, position) => {
    const ing = { ...catalog.normalise(parseIngredientLine(i.text)), guessed: !!i.guessed };
    const line = `${where} "${i.text}"`;
    if (!ing.catalog) errors.push(`${line} matches no catalogue ingredient (parsed name "${ing.name}")`);
    else if (ing.quantity === null && !ing.is_staple) warnings.push(`${line} has no amount`);
    else if (ing.quantity !== null && gramsOf(ing, ing.catalog) === null) {
      warnings.push(`${line} can't be weighed (${ing.unit} of ${ing.name} has no grams_per_unit): left out of macros`);
    }
    if (i.original_text) {
      const orig = catalog.normalise(parseIngredientLine(i.original_text));
      const [g, og] = [gramsOf(ing, ing.catalog), gramsOf(orig, orig.catalog)];
      if (orig.name !== ing.name) {
        errors.push(`${line} is ${ing.name} but original "${i.original_text}" is ${orig.name}`);
      } else if (g && og && !ing.is_staple) {
        // Scaled amounts are rounded (and small ones kept whole), so only flag a clearly wrong scale.
        const scale = g / og / ratio;
        if (scale < 0.6 || scale > 1.6) warnings.push(`${line} isn't ${r.servings}/${r.original_servings} of "${i.original_text}"`);
      }
    }
    return { ...ing, id: i.id, position, original_text: i.original_text ?? null, optional: !!i.optional };
  });
  const macros = estimateMacros(ingredients, r.servings);
  summary.push(`${r.language}  ${String(macros.proteinGPerServing ?? '?').padStart(5)} g  ${String(macros.kcalPerServing ?? '?').padStart(5)} kcal  ${r.title}`);

  adoptRecipes.push(`  (${lit(r.id)}::uuid, ${lit(key)})`);
  for (const i of ingredients) adoptLines.push(`  (${lit(i.id)}::uuid, ${lit(r.id)}::uuid, ${i.position})`);
  inserts.push('', `-- ${r.title.replace(/\n/g, ' ')}`, 'with r as (',
    '  insert into public.recipes (id, household_id, title, source_type, source_url, source_name, image_path, image_source_url,',
    '    servings, original_servings, total_min, prep_min, cook_min, steps, tags, cuisine, kcal_per_serving, protein_g_per_serving,',
    '    macros_estimated, language, difficulty, equipment, ai_generated_recipe)',
    `  select ${lit(r.id)}::uuid, null, ${lit(r.title.trim().slice(0, 200))}, 'seed', ${lit(r.source_url)}, ${lit(r.source_name)}, ${lit(r.image_url)}, ${lit(r.image_source_url ?? r.image_url)},`,
    `    ${r.servings}, ${lit(r.original_servings)}, ${lit(totalMin)}, ${lit(r.prep_min)}, ${lit(r.cook_min)}, ${lit(JSON.stringify(r.steps))}::jsonb,`,
    `    array[${r.tags.map(lit).join(', ')}]::text[], ${lit(r.cuisine)}, ${lit(macros.kcalPerServing)}, ${lit(macros.proteinGPerServing)},`,
    `    ${lit(macros.estimated)}, ${lit(r.language)}, ${lit(r.difficulty)}, ${lit(JSON.stringify(equipment))}::jsonb, ${lit(!!r.ai_generated_recipe)}`,
    `  where not exists (select 1 from public.recipes x where x.id = ${lit(r.id)})`,
    '  returning id',
    ')',
    'insert into public.recipe_ingredients (id, recipe_id, position, name, quantity, unit, aisle, is_staple, guessed, raw_text, original_text, optional)',
    'select v.id, r.id, v.position, v.name, v.quantity, v.unit, v.aisle, v.is_staple, v.guessed, v.raw_text, v.original_text, v.optional',
    'from r, (values',
    ingredients.map((i) => `  (${lit(i.id)}::uuid, ${i.position}, ${lit(i.name)}, ${lit(i.quantity)}::real, ${lit(i.unit)}, ${lit(i.aisle)}::public.aisle, ${lit(i.is_staple)}, ${lit(i.guessed)}, ${lit(i.raw_text)}, ${lit(i.original_text)}, ${lit(i.optional)})`).join(',\n'),
    ') as v(id, position, name, quantity, unit, aisle, is_staple, guessed, raw_text, original_text, optional);');
  // Recipes loaded before difficulty and equipment existed, and households' copies of them, get them now.
  times.push(`  (${lit(r.id)}::uuid, ${lit(totalMin)}, ${lit(r.prep_min)}, ${lit(r.cook_min)})`);
  facets.push(`  (${lit(r.id)}::uuid, ${lit(r.difficulty)}, ${lit(JSON.stringify(equipment))}::jsonb)`);
  for (const i of ingredients) {
    names.push(`  (${lit(i.id)}::uuid, ${lit(r.id)}::uuid, ${i.position}, ${lit(i.name)}, ${lit(i.aisle)}::public.aisle, ${lit(i.is_staple)}, ${lit(i.optional)})`);
  }
  macroRows.push(`  (${lit(r.id)}::uuid, ${lit(macros.kcalPerServing)}::real, ${lit(macros.proteinGPerServing)}::real, ${lit(macros.estimated)})`);
}
// Recipes loaded before they had fixed ids take theirs first; whatever points at them follows
// (on update cascade). Lines are matched by position.
out.push('', '-- Fixed ids for seed recipes loaded before they had them.',
  'update public.recipes s set id = v.id',
  'from (values', adoptRecipes.join(',\n'), ') as v(id, key)',
  `where s.household_id is null and ${keySql('s')} = v.key and s.id <> v.id`,
  '  and not exists (select 1 from public.recipes x where x.id = v.id);',
  'update public.recipe_ingredients i set id = v.id',
  'from (values', adoptLines.join(',\n'), ') as v(id, recipe_id, position)',
  'where i.recipe_id = v.recipe_id and i.position = v.position and i.id <> v.id',
  '  and not exists (select 1 from public.recipe_ingredients x where x.id = v.id);');
out.push(...inserts);
// A seed line by its id; a household's copy of it by position.
const lineOrCopy = '(i.id = v.id or (i.position = v.position and exists ('
  + 'select 1 from public.recipes x where x.id = i.recipe_id and x.copied_from = v.recipe_id)))';
out.push('', '-- Difficulty and equipment for seed recipes (and copies) loaded before those fields existed.',
  'update public.recipes x set difficulty = v.difficulty, equipment = v.equipment',
  'from (values', facets.join(',\n'), ') as v(id, difficulty, equipment)',
  "where (x.id = v.id or x.copied_from = v.id) and x.difficulty is null and x.equipment is null;");
out.push('', '-- Prep, cook and total time for seed recipes (and copies) loaded before prep and cook existed.',
  'update public.recipes x set total_min = v.total_min, prep_min = v.prep_min, cook_min = v.cook_min',
  'from (values', times.join(',\n'), ') as v(id, total_min, prep_min, cook_min)',
  'where (x.id = v.id or x.copied_from = v.id) and x.prep_min is null and x.cook_min is null;');
// When the catalogue gets finer (vegetable stock split from chicken stock),
// recipes already loaded follow: renamed lines find their product again.
out.push('', '-- Ingredient names for seed recipes (and copies) loaded before the catalogue last changed.',
  'update public.recipe_ingredients i set name = v.name, aisle = v.aisle, is_staple = v.is_staple',
  'from (values', names.join(',\n'), ') as v(id, recipe_id, position, name, aisle, is_staple, optional)',
  `where ${lineOrCopy} and i.name is distinct from v.name;`);
// Optional lines are decided per recipe and can change as the library is reviewed.
out.push('', '-- Optional lines for seed recipes (and copies).',
  'update public.recipe_ingredients i set optional = v.optional',
  'from (values', names.join(',\n'), ') as v(id, recipe_id, position, name, aisle, is_staple, optional)',
  `where ${lineOrCopy} and i.optional is distinct from v.optional;`);
out.push('', '-- Their macros follow the catalogue too.',
  'update public.recipes x set kcal_per_serving = v.kcal, protein_g_per_serving = v.protein, macros_estimated = v.estimated',
  'from (values', macroRows.join(',\n'), ') as v(id, kcal, protein, estimated)',
  'where (x.id = v.id or x.copied_from = v.id)',
  '  and (x.kcal_per_serving, x.protein_g_per_serving) is distinct from (v.kcal, v.protein);');
out.push('', 'commit;', '');

console.log(`${recipes.length} recipes, ${recipes.reduce((n, r) => n + r.ingredients.length, 0)} ingredient lines\n`);
console.log('lang  protein   kcal  (per serving, estimated from the catalogue)');
console.log(summary.join('\n'));
if (warnings.length) console.log(`\n${warnings.length} warnings:\n  ${warnings.join('\n  ')}`);
if (errors.length) {
  console.error(`\n${errors.length} errors:\n  ${errors.join('\n  ')}`);
  process.exit(1);
}
if (!checkOnly) {
  writeFileSync(`${root}supabase/seed_library.sql`, out.join('\n'));
  console.log('\nwrote supabase/seed_library.sql');
}
