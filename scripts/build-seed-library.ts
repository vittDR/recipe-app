// Builds supabase/seed_library.sql from supabase/seed/recipes.json.
// Every ingredient line goes through the same parser and catalogue match as
// the import-recipe function, and macros are estimated the same way, so seed
// recipes behave exactly like imported ones.
//
// The catalogue is read from a database that has the migrations and seed.sql
// applied (npm run test:sql leaves one behind as dineamite_test):
//   node scripts/build-seed-library.ts          # check, report, write the SQL
//   node scripts/build-seed-library.ts --check  # check and report only
// Exits 1 when a line doesn't match the catalogue or a recipe is malformed.

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import {
  Catalog, estimateMacros, gramsOf, parseIngredientLine, type CatalogEntry,
} from '../supabase/functions/_shared/logic/ingredients.ts';

interface SeedIngredient { text: string; original_text?: string; guessed?: boolean }
interface SeedRecipe {
  title: string;
  language: 'en' | 'fr' | 'it';
  servings: number;
  original_servings?: number;
  total_min?: number;
  source_type?: string;
  source_name?: string;
  source_url?: string;
  image_url?: string | null;
  image_source_url?: string | null;
  cuisine?: string;
  tags: string[];
  ingredients: SeedIngredient[];
  steps: string[];
}

const root = new URL('..', import.meta.url).pathname;
const checkOnly = process.argv.includes('--check');
const db = process.env.PGDATABASE ?? 'dineamite_test';

const entries = JSON.parse(execFileSync('psql', ['-At', '-d', db, '-c',
  'select coalesce(json_agg(c), \'[]\') from public.ingredient_catalog c'], { encoding: 'utf8' })) as CatalogEntry[];
if (entries.length === 0) throw new Error(`no catalogue in database ${db}: run npm run test:sql first`);
const catalog = new Catalog(entries);
const recipes = JSON.parse(readFileSync(`${root}supabase/seed/recipes.json`, 'utf8')) as SeedRecipe[];

const errors: string[] = [];
const warnings: string[] = [];
const seenUrls = new Set<string>();

function lit(v: unknown): string {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${String(v).replace(/'/g, "''")}'`;
}

const out: string[] = [
  '-- Generated by scripts/build-seed-library.ts from supabase/seed/recipes.json. Do not edit.',
  '-- Seed recipes (household_id null). Re-running skips recipes already loaded (same source_url).',
  'begin;',
];
const summary: string[] = [];

for (const r of recipes) {
  const where = `${r.title}:`;
  if (!['en', 'fr', 'it'].includes(r.language)) errors.push(`${where} language ${r.language}`);
  if (!(r.servings > 0)) errors.push(`${where} servings ${r.servings}`);
  if (!r.source_url) errors.push(`${where} no source_url`);
  else if (seenUrls.has(r.source_url)) errors.push(`${where} duplicate source_url`);
  else seenUrls.add(r.source_url);
  if (r.tags.length > 12) errors.push(`${where} ${r.tags.length} tags (max 12)`);
  if (r.tags.some((t) => t !== t.toLowerCase().trim())) errors.push(`${where} tags must be lowercase`);
  if (r.cuisine && !r.tags.includes(r.cuisine)) warnings.push(`${where} cuisine "${r.cuisine}" missing from tags`);
  if (!r.steps.length) errors.push(`${where} no steps`);
  if (r.image_url?.startsWith('/')) {
    // Photos the app serves itself live in web/public.
    if (!existsSync(`${root}web/public${r.image_url}`)) errors.push(`${where} photo ${r.image_url} not found in web/public`);
  } else if (r.image_url && !r.image_url.startsWith('https://')) errors.push(`${where} image_url must be https:// or /recipe-photos/…`);
  const ratio = r.original_servings ? r.servings / r.original_servings : 1;

  const ingredients = r.ingredients.map((i, position) => {
    const ing = { ...catalog.normalise(parseIngredientLine(i.text)), guessed: !!i.guessed };
    const line = `${where} "${i.text}"`;
    if (!ing.catalog) errors.push(`${line} matches no catalogue ingredient (parsed name "${ing.name}")`);
    else if (ing.quantity === null && !ing.is_staple) warnings.push(`${line} has no amount`);
    else if (ing.quantity !== null && gramsOf(ing, ing.catalog) === null) {
      warnings.push(`${line} can't be weighed (${ing.unit} of ${ing.name} has no grams_per_unit): left out of macros`);
    }
    if (i.original_text) {
      const orig = catalog.normalise(parseIngredientLine(i.original_text));
      const [g, og] = [gramsOf(ing, ing.catalog), gramsOf(orig, orig.catalog)];
      if (orig.name !== ing.name) {
        errors.push(`${line} is ${ing.name} but original "${i.original_text}" is ${orig.name}`);
      } else if (g && og && !ing.is_staple) {
        // Scaled amounts are rounded (and small ones kept whole), so only flag a clearly wrong scale.
        const scale = g / og / ratio;
        if (scale < 0.6 || scale > 1.6) warnings.push(`${line} isn't ${r.servings}/${r.original_servings} of "${i.original_text}"`);
      }
    }
    return { ...ing, position, original_text: i.original_text ?? null };
  });
  const macros = estimateMacros(ingredients, r.servings);
  summary.push(`${r.language}  ${String(macros.proteinGPerServing ?? '?').padStart(5)} g  ${String(macros.kcalPerServing ?? '?').padStart(5)} kcal  ${r.title}`);

  out.push('', `-- ${r.title.replace(/\n/g, ' ')}`, 'with r as (',
    '  insert into public.recipes (household_id, title, source_type, source_url, source_name, image_path, image_source_url,',
    '    servings, original_servings, total_min, steps, tags, cuisine, kcal_per_serving, protein_g_per_serving,',
    '    macros_estimated, language)',
    `  select null, ${lit(r.title.trim().slice(0, 200))}, 'seed', ${lit(r.source_url)}, ${lit(r.source_name)}, ${lit(r.image_url)}, ${lit(r.image_source_url ?? r.image_url)},`,
    `    ${r.servings}, ${lit(r.original_servings)}, ${lit(r.total_min ? Math.round(r.total_min) : null)}, ${lit(JSON.stringify(r.steps))}::jsonb,`,
    `    array[${r.tags.map(lit).join(', ')}]::text[], ${lit(r.cuisine)}, ${lit(macros.kcalPerServing)}, ${lit(macros.proteinGPerServing)},`,
    `    ${lit(macros.estimated)}, ${lit(r.language)}`,
    `  where not exists (select 1 from public.recipes x where x.household_id is null and x.source_url = ${lit(r.source_url)})`,
    '  returning id',
    ')',
    'insert into public.recipe_ingredients (recipe_id, position, name, quantity, unit, aisle, is_staple, guessed, raw_text, original_text)',
    'select r.id, v.* from r, (values',
    ingredients.map((i) => `  (${i.position}, ${lit(i.name)}, ${lit(i.quantity)}::real, ${lit(i.unit)}, ${lit(i.aisle)}::public.aisle, ${lit(i.is_staple)}, ${lit(i.guessed)}, ${lit(i.raw_text)}, ${lit(i.original_text)})`).join(',\n'),
    ') as v(position, name, quantity, unit, aisle, is_staple, guessed, raw_text, original_text);');
}
out.push('', 'commit;', '');

console.log(`${recipes.length} recipes, ${recipes.reduce((n, r) => n + r.ingredients.length, 0)} ingredient lines\n`);
console.log('lang  protein   kcal  (per serving, estimated from the catalogue)');
console.log(summary.join('\n'));
if (warnings.length) console.log(`\n${warnings.length} warnings:\n  ${warnings.join('\n  ')}`);
if (errors.length) {
  console.error(`\n${errors.length} errors:\n  ${errors.join('\n  ')}`);
  process.exit(1);
}
if (!checkOnly) {
  writeFileSync(`${root}supabase/seed_library.sql`, out.join('\n'));
  console.log('\nwrote supabase/seed_library.sql');
}
